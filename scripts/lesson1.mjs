const bad = [];
const SAFE = /^[a-z0-9_-]{1,64}$/;
for (const t of topics) {
  if (!SAFE.test(t.id)) bad.push(`${t.id}: небезопасный id`);
  t.quiz.forEach((q, i) => {
    const at = `${t.id} #${i + 1} (${q.t})`;
    if (['choice', 'listen'].includes(q.t)) {
      if (!q.options.includes(q.a)) bad.push(`${at}: ответа нет среди вариантов`);
      if (new Set(q.options).size !== q.options.length) bad.push(`${at}: повторяются варианты`);
    }
    if (q.t === 'bank' && q.a.trim().split(/\s+/).length < 2) bad.push(`${at}: в мешке меньше двух слов`);
    if (q.t === 'match') {
      if (q.pairs.length < 2 || q.pairs.length > 8) bad.push(`${at}: пар должно быть 2–8`);
      if (new Set(q.pairs.map(p => p[1])).size !== q.pairs.length) bad.push(`${at}: правые части пар повторяются`);
    }
    if (!['fill', 'listen', 'speak'].includes(q.t) && !q.q) bad.push(`${at}: нет текста вопроса`);
  });
  const fronts = t.cards.map(c => c.front);
  if (new Set(fronts).size !== fronts.length) bad.push(`${t.id}: повторяются карточки`);
}
if (bad.length) { console.error('ОШИБКИ:\n' + bad.join('\n')); process.exit(1); }

