let nChoice = 0;
/** Выбор из четырёх: верный ответ ставится на разные места по кругу. */
const choice = (q, a, wrong, hint) => {
  const options = [...wrong];
  options.splice((nChoice++ * 3 + 1) % 4, 0, a);
  return { t: 'choice', q, a, options, ...(hint ? { hint } : {}) };
};
const listen = (say, a, wrong, q = '') => {
  const options = [...wrong];
  options.splice((nChoice++ * 3 + 2) % 4, 0, a);
  return { t: 'listen', q, say, a, options };
};
const speak = (a, q = '', hint = '') => ({ t: 'speak', q, a, say: a, ...(hint ? { hint } : {}) });
const bank = (q, a, extra = [], hint = '') => ({ t: 'bank', q, a, options: extra, ...(hint ? { hint } : {}) });
const fill = (q, a, alt = [], hint = '', say = '') => ({ t: 'fill', q, a, alt, ...(hint ? { hint } : {}), ...(say ? { say } : {}) });
const match = (q, pairs) => ({ t: 'match', q, pairs });
const card = (front, back, ipa = '', example = '', extra = {}) => ({ front, back, ipa, example, ...extra });

