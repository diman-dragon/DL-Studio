execFileSync('zip', ['-r', '-q', 'DL-Studio-lesson-1.zip', 'topics'], { cwd: out });
for (const t of topics) console.log(`${t.id}: теория ${t.theory.length}, карточек ${t.cards.length}, вопросов ${t.quiz.length}`);
console.log(`OK → ${out}`);
